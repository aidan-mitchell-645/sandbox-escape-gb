for code in range(0x20, 0x7F):
    char = chr(code)
    rows = FONT_8X8.get(code, [0]*8)
    comment = f"; '{char}' (${code:02X})"
    tile_bytes = []
    for row in rows:
        lo, hi = row_to_2bpp(row)
        tile_bytes.append(lo)
        tile_bytes.append(hi)
    hex_pairs = ", ".join(f"${b:02X}" for b in tile_bytes)
    lines.append(f"    DB {hex_pairs}  {comment}\n")

with open(out_path, "w") as f:
    f.writelines(lines)

print(f"Generated {out_path} ({len(lines)-3} character tiles)")
