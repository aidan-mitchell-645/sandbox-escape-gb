def bit_reverse(b):
    """Reverse the bit order of a byte: bit7↔bit0, bit6↔bit1, etc.
    GB hardware renders bit 7 of each plane byte as the LEFTMOST pixel.
    Our font bitmaps are stored with bit 0 as leftmost (common convention),
    so we must reverse before writing to the tile data.
    """
    result = 0
    for i in range(8):
        if b & (1 << i):
            result |= (1 << (7 - i))
    return result

def row_to_2bpp(row_byte):
    """Convert an 8-bit row bitmap to two GB 2bpp bytes (lo, hi).
    Bit-reverses the byte so bit7=leftmost pixel as GB hardware requires.
    pixel=1 → colour 3 (both planes set) = bright green on GBC, black on DMG.
    """
    r = bit_reverse(row_byte)
    return r, r   # lo == hi → colour 3 for every lit pixel

